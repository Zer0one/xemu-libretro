"""Generate the checked-in security catalogue from a local MAME chihiro.cpp.
No network access. Usage: gen-chihiro-media-catalog.py SOURCE --revision COMMIT
"""
import argparse
import hashlib
from pathlib import Path
import re

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('source', type=Path)
p.add_argument('--revision', required=True)
p.add_argument('--output', type=Path, default=Path('ui/libretro-chihiro-media-table.h'))
a = p.parse_args()
assert re.fullmatch(r'[0-9a-f]{40}', a.revision)
raw = a.source.read_bytes()
text = re.sub(r'/\*.*?\*/|//[^\n]*', '', raw.decode(), flags=re.S)
parents = dict(re.findall(r'GAME\(\s*\d+,\s*(\w+),\s*(\w+),', text))
rows = []
for name, block in re.findall(r'ROM_START\(\s*(\w+)\s*\)(.*?)ROM_END', text, re.S):
    discs = re.findall(r'DISK_IMAGE_READONLY\(\s*"([^"]+)",\s*0,\s*SHA1\(([0-9a-f]{40})\)', block)
    keys = re.findall(r'ROM_LOAD\(\s*"([^"/]+\.(?:data|pic))"[^\n]*?SHA1\(([0-9a-f]{40})\)', block)
    if not discs:
        continue
    assert len(keys) == 1, (name, keys)
    for disc, sha in discs:
        rows.append((disc, sha, name, parents.get(name, ''), *keys[0]))
assert len(rows) >= 30 and len({r[0] for r in rows}) == len(rows)
by_set = {r[2]: r for r in rows}
lines = [
    '/* SPDX-License-Identifier: BSD-3-Clause',
    ' * Metadata from MAME, copyright Samuele Zannoli.',
    ' * See licenses/mame-chihiro-catalog.license.txt.',
    f' * Revision: {a.revision}',
    f' * Source SHA256: {hashlib.sha256(raw).hexdigest()}',
    ' * Generated by scripts/gen-chihiro-media-catalog.py; do not edit.',
    ' * Association data is not a claim of playable game support.',
    ' */',
    'static const XemuChihiroMedia media_table[] = {',
]
for disc, sha, name, parent, key, keysha in rows:
    # A merged parent archive is useful only if it contains the same game key.
    if parent not in by_set or by_set[parent][5] != keysha:
        parent = ''
    lines.append('    { ' + ', '.join('"' + s + '"' for s in (disc, sha, name, parent, key, keysha)) + ' },')
lines.append('};\n')
a.output.write_text('\n'.join(lines))
print(f'{len(rows)} CHD/security associations written to {a.output}')
